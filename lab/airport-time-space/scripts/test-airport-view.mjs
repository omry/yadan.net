import assert from 'node:assert/strict';
import {selectAirportLabels} from '../dist/airport-view.js';
import {prepare,SpaceSolver} from '../dist/engine.js';
import {filterObservations} from '../dist/observations.js';
const airports=Array.from({length:21},(_,i)=>({id:`A${String(i).padStart(2,'0')}`,name:'Test'}));
const routes=[];
for(let i=1;i<21;i++)routes.push({from_airport:airports[i].id,to_airport:'A00',minutes:240,aircraft:'Boeing 787-9'});
for(let i=0;i<10;i++)routes.push({from_airport:'A00',to_airport:'A01',minutes:240,aircraft:'Boeing 787-9'});
routes.push({from_airport:'A02',to_airport:'A01',minutes:60,aircraft:'Airbus A320'});
const source=prepare({airports,routes}),saved=JSON.stringify(source),solver=new SpaceSolver(source,71);solver.initializeAll('space');const points=JSON.stringify(solver.points);
const view=selectAirportLabels(source);
assert.equal(view.count,3,'Top 10% rounds up');
assert.deepEqual(view.indices,[0,1,2],'Ties use airport code');
assert.equal(view.ranked[0].incoming,20);assert.equal(view.ranked[0].outgoing,1);
assert.equal(view.ranked[1].incoming,2,'Repeated flight samples count one incoming connection');
assert.equal(view.ranked[2].incoming,0,'An outgoing connection is not an incoming connection');
assert.deepEqual(selectAirportLabels(source,'all').indices,source.order);
const filtered=filterObservations(source,{aircraft:'widebody',minHours:3});
assert.equal(selectAirportLabels(filtered).ranked.find(a=>a.id==='A01').incoming,1,'Rank after observation filtering');
const excludedView=selectAirportLabels({...source,excludedEdges:[{a:0,b:1}]});
assert.equal(excludedView.ranked.find(a=>a.id==='A01').incoming,1,'Triangle exclusions affect hub ranking while original source rows remain');
assert.equal(excludedView.ranked.find(a=>a.id==='A00').incoming,19,'Both directions of an excluded constraint leave the active network');
assert.equal(JSON.stringify(source),saved);assert.equal(JSON.stringify(solver.points),points,'View changes cannot move fitted points');
assert.throws(()=>selectAirportLabels(source,'invalid'),/hubs or all/);
console.log(JSON.stringify({checks:'passed',hubSelection:'directional, distinct, filtered, deterministic, display only'}));
